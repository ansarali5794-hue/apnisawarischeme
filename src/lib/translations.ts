export const getSavedLanguage = (): LanguageType => {
  try {
    const saved = localStorage.getItem('as_app_language') as LanguageType;
    if (saved && (saved === 'en' || saved === 'ur' || saved === 'sd')) {
      return saved;
    }
  } catch {}
  return 'ur'; // default to Urdu
};

export const saveLanguage = (lang: LanguageType) => {
  try {
    localStorage.setItem('as_app_language', lang);
  } catch {}
};

